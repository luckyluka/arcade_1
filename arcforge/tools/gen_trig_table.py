#!/usr/bin/env python3
"""Generate the integer trig table (ROADMAP P0.4).

Writes two byte-deterministic artifacts from one formula:

  c/gen/trig_table.h   -- what the C compiler (M4) includes; the C build
                          never calls libm, so this header is the only
                          trig both tools see.
  tests/trig_table.json-- the same values for tests and tooling.

Formula: int(round(cos|sin(deg) * 1000000)) for deg in -180..180
inclusive, round-half-even exactly as Python's round() -- the oracle in
tools/arcforge_ref.py computes COS/SIN the same way, and
tests/test_trig_table.py pins all three views (header, JSON, oracle)
equal. No exact .5 tie occurs in this table, so the tie rule is
specified but never decides a value.

Usage:
  python3 tools/gen_trig_table.py          # write both files
  python3 tools/gen_trig_table.py --check  # verify, write nothing, rc=1 if stale

No timestamps, no randomness: the output depends only on the formula.
"""
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER_PATH = ROOT / "c" / "gen" / "trig_table.h"
JSON_PATH = ROOT / "tests" / "trig_table.json"

DEG_MIN, DEG_MAX = -180, 180
SCALE = 1000000
COUNT = DEG_MAX - DEG_MIN + 1


def table():
    """(cos, sin) rows, index = deg - DEG_MIN. The formula of record."""
    cos = [int(round(math.cos(math.radians(d)) * SCALE)) for d in range(DEG_MIN, DEG_MAX + 1)]
    sin = [int(round(math.sin(math.radians(d)) * SCALE)) for d in range(DEG_MIN, DEG_MAX + 1)]
    return cos, sin


def _array(name, values):
    lines = [f"static const int32_t {name}[TRIG_COUNT] = {{"]
    for d, v in zip(range(DEG_MIN, DEG_MAX + 1), values):
        lines.append(f"    {v:8d},  /* {d:4d} */")
    lines.append("};")
    return lines


def header_bytes(cos, sin):
    lines = [
        "/* trig_table.h -- GENERATED by tools/gen_trig_table.py. DO NOT EDIT.",
        " *",
        " * int(round(cos|sin(deg) * 1000000)) for deg in -180..180 inclusive,",
        " * round-half-even as Python's round(). The C build never calls libm:",
        " * this header is the only trig. Index = deg + 180. Regenerate with",
        " * python3 tools/gen_trig_table.py (add --check to verify).",
        " */",
        "#ifndef ARCFORGE_TRIG_TABLE_H",
        "#define ARCFORGE_TRIG_TABLE_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define TRIG_DEG_MIN ({DEG_MIN})",
        f"#define TRIG_DEG_MAX {DEG_MAX}",
        f"#define TRIG_SCALE {SCALE}",
        f"#define TRIG_COUNT {COUNT}",
        "",
    ]
    lines += _array("trig_cos", cos)
    lines.append("")
    lines += _array("trig_sin", sin)
    lines.append("")
    lines.append("#endif  /* ARCFORGE_TRIG_TABLE_H */")
    return ("\n".join(lines) + "\n").encode("ascii")


def json_bytes(cos, sin):
    doc = {
        "description": "integer trig table (P0.4): int(round(cos|sin(deg)*1e6)), deg -180..180, index = deg + 180",
        "scale": SCALE,
        "deg_min": DEG_MIN,
        "deg_max": DEG_MAX,
        "cos": cos,
        "sin": sin,
    }
    return (json.dumps(doc, indent=2) + "\n").encode("ascii")


def artifacts():
    cos, sin = table()
    return {HEADER_PATH: header_bytes(cos, sin), JSON_PATH: json_bytes(cos, sin)}


def main(argv):
    written = artifacts()
    check = "--check" in argv
    stale = []
    for path, data in written.items():
        current = path.read_bytes() if path.exists() else None
        if current == data:
            status = "fresh"
        elif check:
            stale.append(path)
            status = "STALE"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
            status = "written"
        print(f"{status:8} {path.relative_to(ROOT)}")
    if stale:
        print("run: python3 tools/gen_trig_table.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
