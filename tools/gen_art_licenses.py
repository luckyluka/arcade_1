#!/usr/bin/env python3
"""tools/gen_art_licenses.py — write art/ART_LICENSES.md from the manifests.

Every asset manifest in the repository (a JSON file with "format": 1) is
read, and every asset that carries a provenance block lands in the
generated summary: which manifest it came from, how it was made, and the
terms it ships under (ROADMAP_V4 card 7.1; the schema is in
docs/art/PROVENANCE.md).

The file it writes is GENERATED — never hand-edit it; run this instead:

    make art-licenses

Stdlib only.
"""
import glob
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import arc1_assetc as assetc            # noqa: E402  (the writer lives there)


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, "art", "ART_LICENSES.md")

    manifests = []
    for path in sorted(glob.glob(os.path.join(root, "programs", "**", "*.json"),
                                 recursive=True)):
        try:
            with open(path) as f:
                doc = json.load(f)
        except (OSError, ValueError):
            continue
        if not isinstance(doc, dict) or doc.get("format") != 1:
            continue
        if not any(doc.get(g) for g in ("sprites", "animations", "maps")):
            continue
        manifests.append((os.path.relpath(path, root), doc))

    merged = {"sprites": [], "animations": [], "maps": []}
    for rel, doc in manifests:
        for group in merged:
            for item in doc.get(group, []):
                if not isinstance(item, dict) or item.get("provenance") is None:
                    continue
                item = dict(item)
                item["_source"] = rel
                merged[group].append(item)

    assetc.write_licenses(out, merged,
                          note="generated by tools/gen_art_licenses.py from "
                               "%d manifest(s) — DO NOT EDIT" % len(manifests))
    print("art-licenses: %s (%d manifest(s), %d asset(s))"
          % (out, len(manifests),
             sum(len(merged[g]) for g in merged)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
