/* probe8: the same 5x2 tilemap drawn with the 1-bit TILEMAP command. */
#include "include/arcade1.h"

#define RGB(r, g, b) (unsigned)((((r) & 31) << 11) | (((g) & 63) << 5) | ((b) & 31))

#define COLS 5
#define ROWS 2
#define TW   16
#define TH   8

static unsigned cells[COLS * ROWS];
static const unsigned char tile[TH * ((TW + 7) / 8)] = {
    0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
    0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
    0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
    0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
    0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
    0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
    0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
    0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
};

int main(void)
{
    int r, c;
    static const unsigned short tints[5] = { 0xF800, 0x07E0, 0x001F, 0xFFE0, 0xF81F };

    for (r = 0; r < ROWS; r++)
        for (c = 0; c < COLS; c++)
            cells[r * COLS + c] = 1u | ((unsigned)tints[c] << 16);

    for (;;) {
        arcade1_clear(RGB(0, 0, 0));
        arcade1_tilemap(0, 20, cells, tile, COLS, ROWS, TW, TH);
        arcade1_present();
    }
}
