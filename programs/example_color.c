/* --- Palette ---------------------------------------------------------------
 * Bank 0: sixteen distinct RGB565 colours. Bank 1 (entries 16..19): the
 * four the arrow sprite uses. */

static const unsigned short pal0[16] = {
    0x0000, /* 0 black (cleared background) */
    0xF800, /* 1 red */
    0x07E0, /* 2 green */
    0x001F, /* 3 blue */
    0xFFE0, /* 4 yellow */
    0xF81F, /* 5 magenta */
    0x07FF, /* 6 cyan */
    0xFFFF, /* 7 white */
    0x8410, /* 8 gray */
    0xFD20, /* 9 orange */
    0x8010, /* 10 purple */
    0x0410, /* 11 dark green */
    0x8000, /* 12 dark red */
    0x0010, /* 13 dark blue */
    0xC618, /* 14 light gray */
    0xEF5D, /* 15 pale gray */
};

static const unsigned short pal1[4] = {
    0x001F, /* 16 blue   */
    0xFFE0, /* 17 yellow */
    0x07FF, /* 18 cyan   */
    0xFFFF, /* 19 white  */
};

static void pal_init(void)
{
    gfx_pal_upload(0, pal0, 16);   /* bank 0: entries 0..15   */
    gfx_pal_upload(16, pal1, 4);   /* bank 1: entries 16..19  */
}

/* --- Map -------------------------------------------------------------------
 * 40x20 cells of 32-bit words: [15:0] tile index (0 = empty, the cleared
 * background shows through), [19:16] palette bank, [20] flip X, [21]
 * flip Y. Built once at boot into RAM; the device reads it from there. */

#define MAP_COLS 40
#define MAP_ROWS 20

static unsigned int map[MAP_COLS * MAP_ROWS];

static void map_init(void)
{
    for (int r = 0; r < MAP_ROWS; r++)
        for (int c = 0; c < MAP_COLS; c++) {
            unsigned int cell;
            if (r % 6 == 2 && c % 6 == 3)
                cell = 0;                              /* empty: background */
            else if (r == 0 || c == 0 || r == MAP_ROWS - 1 || c == MAP_COLS - 1)
                cell = 1;                              /* red frame */
            else if (r % 8 == 5 && c % 8 == 6)
                cell = 2 | (1u << 16);                /* checker, bank 1 */
            else if ((r + c) % 7 == 0)
                cell = 4 | (1u << 20);                /* filled, flip X */
            else if (r % 4 == 3 && c % 5 == 4)
                cell = 3 | (1u << 21);                /* stripes, flip Y */
            else
                cell = 2;                             /* checker, bank 0 */
            map[r * MAP_COLS + c] = cell;
        }
}

/* --- Frame loop ------------------------------------------------------------
 * The camera position is the state worth observing, so it lives at file
 * scope: `arcade1 run ... --vars cam_x,cam_y` reads it by name. */

static int cam_x, cam_y;

int main(void)
{
    pal_init();
    map_init();

    unsigned t = 0;
    for (;;) {
        cam_x = (int)((t * 2u) % 160u);   /* world px, wraps over 80 frames */
        cam_y = (int)((t / 2u) % 40u);   /* world px, wraps over 80 frames */
        arcade1_clear(0x0000);
        arcade1_cam(cam_x, cam_y);
        arcade1_tilemap4(0, 0, map, tiles, MAP_COLS, MAP_ROWS, TILE_W, TILE_H);
        int sx = 60 + (int)((t / 4u) % 320u);
        int sy = 40 + (int)((t / 6u) % 160u);
        arcade1_sprite4(sx, sy, sprite, SPR_W, SPR_H, 1, 1 /* flip X */);
        arcade1_present();
        t++;
    }
    return 0;
}
