/* Draw a string at (x, y), one glyph per 8x8 cell, left to right. Characters
 * outside 0x20..0x5F are skipped but still advance the cursor, so columns
 * stay aligned. */
static inline void text_draw(int x, int y, const char *s, unsigned color)
{
    for (; *s; s++) {
        unsigned char c = (unsigned char)*s;
        if (c >= 0x20u && c <= 0x5Fu)
            arcade1_sprite(x, y, &arcade1_text_font[(c - 0x20u) * 8u],
                           ARCADE1_TEXT_GLYPH_W, ARCADE1_TEXT_GLYPH_H, color);
        x += ARCADE1_TEXT_CELL;
    }
}

/* Draw `value` as exactly `digits` decimal digits, zero-padded; the least
 * significant digit sits in the rightmost cell at x + (digits-1)*8. */
static inline void text_u32(int x, int y, unsigned value, int digits,
                            unsigned color)
{
    char buf[2];
    buf[1] = '\0';
    for (int i = digits - 1; i >= 0; i--) {
        buf[0] = (char)('0' + (int)(value % 10u));
        text_draw(x + i * ARCADE1_TEXT_CELL, y, buf, color);
        value /= 10u;
    }
}

