def main():
    out = ["/* starfall_assets.h -- GENERATED by gen_starfall_assets.py. */\n",
           "#ifndef STARFALL_ASSETS_H\n#define STARFALL_ASSETS_H\n\n"]
    pal = []
    pal += [0x0000, 0x07FF, 0xFFFF, 0xFC00] + [0] * 12   # 0 ship
    pal += [0x0000, 0xFFE0, 0xFFFF, 0x0000] + [0] * 12   # 1 bullet
    pal += [0x0000, 0xF800, 0xFFFF, 0xFC00] + [0] * 12   # 2 enemy A
    pal += [0x0000, 0x781F, 0xFFE0, 0xFFFF] + [0] * 12   # 3 enemy B
    pal += [0x0000, 0xF81F, 0xFFFF, 0x0000] + [0] * 12   # 4 enemy bullet
    pal += [0x0000, 0xFFFF, 0xF800, 0x07E0] + [0] * 12   # 5 HUD
    body = ["    0x%04X," % v for v in pal]
    out.append("static const unsigned short palette[%d] = {\n%s\n};\n\n"
               % (len(pal), "\n".join(body)))
    out.append("#define PAL_N %d\n\n" % len(pal))
    out.append("#define BANK_SHIP 0\n#define BANK_BULLET 1\n#define BANK_ENEMY 2\n"
               "#define BANK_ENEMY2 3\n#define BANK_EBULLET 4\n#define BANK_HUD 5\n\n")

    out.append(pack("ship_img", SHIP, 16) + "\n")
    out.append(pack("enemy_a_img", ENEMY_A, 16) + "\n")
    out.append(pack("enemy_b_img", ENEMY_B, 16) + "\n")
    out.append(pack("bullet_img", BULLET, 4) + "\n")
    out.append(pack("ebullet_img", EBULLET, 4) + "\n")
    out.append(pack("heart_img", HEART, 8) + "\n")

    for ch in "0123456789":
        out.append(pack("glyph_%s" % ch, glyph(ch), 6) + "\n")
    out.append(pack("glyph_space", ["000000"] * 8, 6) + "\n")
    alpha = []
    for ch in "ABCDEFGHIJKLMNOPQRSTUVWXYZ":
        out.append(pack("glyph_%s" % ch, glyph(ch), 6) + "\n")
        alpha.append("glyph_%s" % ch)
    out.append("static const unsigned char *const digit_img[10] = { %s };\n\n"
               % ", ".join("glyph_%s" % d for d in "0123456789"))
    out.append("static const unsigned char *const alpha_img[26] = { %s };\n\n"
               % ", ".join(alpha))
    out.append("#endif /* STARFALL_ASSETS_H */\n")

    text = "".join(out)
    with open(sys.argv[1] if len(sys.argv) > 1 else "starfall_assets.h", "w") as f:
        f.write(text)
    print("wrote %d bytes" % len(text))


if __name__ == "__main__":
    main()
