def pack(name, rows, w):
    assert w % 2 == 0, name
    body = []
    for r in rows:
        r = r.replace(".", "0")
        assert len(r) == w, (name, len(r), w, r)
        bs = [(int(r[i], 16) << 4) | int(r[i + 1], 16) for i in range(0, w, 2)]
        body.append("    " + ", ".join("0x%02X" % x for x in bs) + ",")
    return "static const unsigned char %s[%d] = {\n%s\n};\n" % (
        name, len(rows) * (w // 2), "\n".join(body))


def glyph(ch):
    pat = FONT[ch] if ch in FONT else ["....."] * 7
    rows = []
    for y in range(8):
        row = (pat[y] if y < 7 else ".....") + "0"
        rows.append(row.replace(".", "0").replace("#", "1"))
    return rows


